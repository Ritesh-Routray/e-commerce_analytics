"""Generate reports/FINDINGS.md from computed results, so every number in it is reproducible."""
from __future__ import annotations

import pandas as pd

from . import config


def _money(x: float) -> str:
    return f"R$ {x / 1e6:,.2f}M"


def write_findings(results: dict, model_result: dict | None) -> None:
    li = results["late_impact"]
    stages = results["stage_breakdown"].set_index("outcome")
    states = results["state_performance"]
    dist = results["distance_effect"]
    tiers = results["seller_tiers"].set_index("tier")
    delay = results["delay_vs_review"].set_index("delay_bucket")
    repeat = results["repeat_by_delivery"].set_index("first_delivery")
    monthly = results["monthly_kpis"]
    cohort = results["cohort_retention"]

    extra = stages.loc["Late"] - stages.loc["On time"]
    peak = monthly.loc[monthly["late_rate"].idxmax()]
    worst_state = states.iloc[0]
    best_state = states.sort_values("late_rate").iloc[0]
    near, far = dist.iloc[0], dist.iloc[-2]
    month1 = cohort[1].mean()

    lines: list[str] = []
    add = lines.append
    add("# Findings\n")
    add("_Generated by `scripts/run_pipeline.py`. Re-run the pipeline to refresh every number._\n")

    add("## 1. Late delivery is rare but it is what drives bad reviews\n")
    add(
        f"- {li['delivered_orders']:,} delivered orders; **{li['late_rate']:.1%}** arrived after the promised date "
        f"({_money(li['revenue_in_late_orders'])} of {_money(li['revenue_total'])} item revenue)."
    )
    add(
        f"- Average review: **{li['avg_review_on_time']:.2f}** on time vs **{li['avg_review_late']:.2f}** late, a gap of "
        f"{li['review_gap']:.2f} stars (95% CI {li['review_gap_ci_low']:.2f} to {li['review_gap_ci_high']:.2f})."
    )
    add(
        f"- One-star reviews: {li['one_star_share_on_time']:.1%} of on-time orders vs "
        f"**{li['one_star_share_late']:.1%}** of late orders."
    )
    add(
        f"- The penalty grows with the delay: {delay.loc['1-3 days late', 'avg_review']:.2f} stars at 1-3 days late, "
        f"{delay.loc['8+ days late', 'avg_review']:.2f} at 8+ days. Arriving 8+ days early earns only "
        f"{delay.loc['8+ days early', 'avg_review'] - delay.loc['On time (0-3 early)', 'avg_review']:+.2f} stars over arriving on time.\n"
    )
    add("![Review by delay](../outputs/figures/02_review_score_by_delay.png)\n")

    add("## 2. Delays accumulate in carrier transit, not in the warehouse\n")
    add(
        f"Late orders take {stages.loc['Late', 'delivery_days']:.1f} days end to end vs {stages.loc['On time', 'delivery_days']:.1f} for on-time ones. "
        f"Of the extra {extra['delivery_days']:.1f} days, **{extra['transit_days']:.1f}** are carrier transit, "
        f"{extra['handling_days']:.1f} seller handling and {extra['approval_days']:.1f} payment approval. "
        "Seller handling is also slower on late orders, so both matter, but transit dominates.\n"
    )
    add("![Time by stage](../outputs/figures/03_time_by_stage.png)\n")

    add("## 3. Geography: the promise is padded, but not enough far from São Paulo\n")
    add(
        f"- Highest late rate by destination: **{worst_state['customer_state']} ({worst_state['late_rate']:.1%})**; "
        f"lowest among large states: {best_state['customer_state']} ({best_state['late_rate']:.1%})."
    )
    add(
        f"- Orders under 100 km are late {near['late_rate']:.1%} of the time; at 1,500-2,500 km the rate is "
        f"{far['late_rate']:.1%}. The promised window already grows from {near['median_promised_days']:.0f} to "
        f"{far['median_promised_days']:.0f} days (median delivery goes from {near['median_delivery_days']:.0f} to "
        f"{far['median_delivery_days']:.0f}), so far lanes get a bigger cushion, yet they are still late more often: "
        "long routes are less predictable, not just slower.\n"
    )
    add("![Late rate by state](../outputs/figures/04_late_rate_by_state.png)\n")
    add("![Distance effect](../outputs/figures/05_distance_effect.png)\n")

    add("## 4. Lateness comes in platform-wide waves\n")
    nov = monthly[monthly["purchase_month"] == "2017-11-01"]
    calm = monthly[monthly["purchase_month"].between("2017-05-01", "2017-08-01")]["late_rate"].mean()
    nov_text = (
        f"November 2017, the busiest month on record, ran at {nov['late_rate'].iloc[0]:.1%}. "
        if len(nov)
        else ""
    )
    add(
        f"Mid-2017 was calm ({calm:.1%} late on average). {nov_text}"
        f"The single worst month was **{peak['purchase_month']:%B %Y}** at {peak['late_rate']:.1%}. "
        "These swings are platform-level, which is why a model trained on one wave transfers poorly to the next "
        "(see section 7).\n"
    )
    add("![Monthly trend](../outputs/figures/01_monthly_orders_and_late_rate.png)\n")

    add("## 5. Sellers: a small group is far less reliable than the rest\n")
    pr, wa, he = tiers.loc["Priority"], tiers.loc["Watch"], tiers.loc["Healthy"]
    add(
        f"Among sellers with at least 30 delivered orders, **{int(pr['sellers'])} Priority** sellers "
        f"(shrunk late rate at least 2x platform) average a {pr['avg_late_rate']:.1%} late rate and "
        f"{pr['avg_review']:.2f}-star reviews, versus {he['avg_late_rate']:.1%} and {he['avg_review']:.2f} for "
        f"{int(he['sellers'])} Healthy sellers. Priority sellers account for only {pr['revenue_share']:.1%} of tier revenue, "
        f"so intervening costs little. {int(wa['sellers'])} more sit on a Watch list ({wa['revenue_share']:.1%} of revenue).\n"
    )
    add("![Seller scorecard](../outputs/figures/07_seller_scorecard.png)\n")

    add("## 6. Repeat purchase is rare, and only slightly lower after a late first order\n")
    add(
        f"Only about {repeat['repeat_rate'].mean():.1%} of customers buy again within 180 days. By first-order outcome: "
        f"on-time {repeat.loc['On time', 'repeat_rate']:.2%} "
        f"(95% CI {repeat.loc['On time', 'ci_low']:.2%}-{repeat.loc['On time', 'ci_high']:.2%}) vs late "
        f"{repeat.loc['Late', 'repeat_rate']:.2%} "
        f"(95% CI {repeat.loc['Late', 'ci_low']:.2%}-{repeat.loc['Late', 'ci_high']:.2%}). "
        "Late-first customers repeat a little less, but the intervals nearly overlap and the absolute numbers are tiny: "
        f"on average only {month1:.1%} of a monthly cohort buys again the next month. "
        "The measurable cost of lateness here is in reviews, not in repeat revenue.\n"
    )
    add("![Repeat purchase](../outputs/figures/06_repeat_purchase_by_first_delivery.png)\n")

    if model_result:
        m = model_result["metrics"]["mean_over_folds"]
        pooled = model_result["metrics"]["pooled_out_of_fold_lightgbm"]
        abl = model_result["ablation"].set_index("feature_set")
        add("## 7. Can we predict lateness at checkout? Only modestly\n")
        add(
            "Walk-forward evaluation (train on orders already delivered, score the next two months, five folds):\n"
        )
        add(f"- LightGBM: mean ROC AUC **{m['lightgbm']['roc_auc']:.3f}**, top-decile lift **{m['lightgbm']['lift_at_10pct']:.2f}x**.")
        add(
            f"- Logistic regression baseline: ROC AUC {m['logistic_regression']['roc_auc']:.3f}, "
            f"lift {m['logistic_regression']['lift_at_10pct']:.2f}x. The simple model is as good, so the extra complexity "
            "of boosting is not earning its keep."
        )
        add(
            f"- Flagging the riskiest 10% of orders catches {pooled['recall_at_10pct']:.0%} of late orders "
            f"({pooled['precision_at_10pct']:.1%} precision vs {pooled['base_rate']:.1%} base rate)."
        )
        add(
            "- Feature ablation: adding seller/lane/regime history _lowered_ AUC "
            f"(order-only {abl.loc['order_only', 'mean_roc_auc']:.3f}, +history "
            f"{abl.loc['plus_seller_lane_history', 'mean_roc_auc']:.3f}, +regime "
            f"{abl.loc['plus_regime_history', 'mean_roc_auc']:.3f}), because those features track one period's "
            "delay wave instead of durable seller quality. The shipped model uses order-level features only."
        )
        g = model_result["folds"].query("model == 'lightgbm'")
        add(
            f"- Performance is uneven: LightGBM AUC ranges from {g['roc_auc'].min():.2f} to {g['roc_auc'].max():.2f} "
            "across folds (the weakest being the latest period). "
            "Treat the model as a triage aid for ranking orders, not a probability forecaster.\n"
        )
        add("![Walk-forward AUC](../outputs/figures/08_model_walk_forward_auc.png)\n")
        add("![Risk deciles](../outputs/figures/09_model_risk_deciles.png)\n")

    add("## Caveats\n")
    add("- Observational data: reviews and lateness are correlated, not proven causal.")
    add("- Orders still in transit when the data ends are excluded, which slightly understates late rates for the newest months.")
    add("- Seller and customer locations are zip-prefix centroids, so distances are approximate.")
    add("- The dataset covers Sept 2016 to Oct 2018 and is a sample of one marketplace.")

    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "FINDINGS.md").write_text("\n".join(lines), encoding="utf-8")
